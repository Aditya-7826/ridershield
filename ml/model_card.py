"""Write simple Markdown model cards next to the code (ml/model_cards/)."""
from __future__ import annotations

from datetime import datetime

from ml.config import MODEL_CARDS_DIR


def write_model_card(name: str, title: str, sections: dict[str, str]) -> str:
    """Write ml/model_cards/<name>.md and return its path."""
    MODEL_CARDS_DIR.mkdir(parents=True, exist_ok=True)
    lines = [f"# Model card: {title}", "", f"_Generated by `scripts/train.py` on {datetime.now():%Y-%m-%d}._", ""]
    for heading, body in sections.items():
        lines += [f"## {heading}", "", body.strip(), ""]
    path = MODEL_CARDS_DIR / f"{name}.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return str(path)


def md_table(df) -> str:
    """Tiny DataFrame -> Markdown table (avoids the optional tabulate dependency)."""
    cols = list(df.columns)
    rows = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        rows.append("| " + " | ".join(_fmt(r[c]) for c in cols) + " |")
    return "\n".join(rows)


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.3f}" if abs(v) < 10 else f"{v:.1f}"
    return str(v)
